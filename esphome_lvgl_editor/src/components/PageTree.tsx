import React, { useState } from 'react';
import { ChevronRight, ChevronDown, Layers } from 'lucide-react';
import { useEditorStore } from '../store/editorStore';
import { Widget } from '../types/widgets';

export const PageTree: React.FC = () => {
  const {
    config,
    currentPageId,
    setCurrentPage,
    selectWidget,
    selectWidgetByPath,
    selectedWidgetId,
    selectedWidgetPath
  } = useEditorStore();
  const [expandedPages, setExpandedPages] = useState<Set<string>>(new Set([currentPageId]));
  const [expandedWidgets, setExpandedWidgets] = useState<Set<string>>(new Set());

  const togglePage = (pageId: string) => {
    const newExpanded = new Set(expandedPages);
    if (newExpanded.has(pageId)) {
      newExpanded.delete(pageId);
    } else {
      newExpanded.add(pageId);
    }
    setExpandedPages(newExpanded);
  };

  const toggleWidget = (widgetKey: string) => {
    const newExpanded = new Set(expandedWidgets);
    if (newExpanded.has(widgetKey)) {
      newExpanded.delete(widgetKey);
    } else {
      newExpanded.add(widgetKey);
    }
    setExpandedWidgets(newExpanded);
  };

  const handlePageClick = (pageId: string) => {
    setCurrentPage(pageId);
    if (!expandedPages.has(pageId)) {
      togglePage(pageId);
    }
  };

  const getWidgetLabel = (widget: Widget) => {
    if (widget.id && !(widget as any)._autoGeneratedId) {
      return widget.id;
    }
    if (widget.type === 'label' && (widget as any).text) {
      return (widget as any).text;
    }
    if (widget.type === 'checkbox' && (widget as any).text) {
      return (widget as any).text;
    }
    if (widget.type === 'button') {
      return 'Button';
    }
    return 'unnamed';
  };

  const renderWidget = (
    widget: Widget,
    depth: number,
    path: string,
    pageId: string,
    isTopLayerSection = false
  ) => {
    const hasChildren = widget.type === 'obj' && (widget as any).widgets?.length > 0;
    const widgetKey = isTopLayerSection ? `top:${widget.id || path}` : `page:${pageId}:${path}`;
    const isExpanded = expandedWidgets.has(widgetKey);
    const isSelected = isTopLayerSection
      ? selectedWidgetId === widget.id
      : currentPageId === pageId && selectedWidgetPath === path;

    const handleWidgetClick = () => {
      if (isTopLayerSection) {
        selectWidget(widget.id || null);
        return;
      }

      if (currentPageId !== pageId) {
        setCurrentPage(pageId);
      }
      selectWidgetByPath(path);
    };

    return (
      <div key={widgetKey}>
        <div
          onClick={handleWidgetClick}
          style={{
            display: 'flex',
            alignItems: 'center',
            padding: '4px 8px',
            paddingLeft: `${depth * 16 + 8}px`,
            cursor: 'pointer',
            backgroundColor: isSelected ? '#2a4a6a' : 'transparent',
            borderLeft: isSelected ? '3px solid #61dafb' : '3px solid transparent',
            color: isSelected ? '#fff' : '#ccc',
            fontSize: '12px',
            transition: 'all 0.15s ease'
          }}
          onMouseEnter={(e) => {
            if (!isSelected) {
              e.currentTarget.style.backgroundColor = '#2c2c2c';
            }
          }}
          onMouseLeave={(e) => {
            if (!isSelected) {
              e.currentTarget.style.backgroundColor = 'transparent';
            }
          }}
        >
          {hasChildren && (
            <button
              onClick={(e) => {
                e.stopPropagation();
                toggleWidget(widgetKey);
              }}
              style={{
                background: 'none',
                border: 'none',
                color: '#888',
                cursor: 'pointer',
                padding: '0 4px 0 0',
                display: 'flex',
                alignItems: 'center'
              }}
            >
              {isExpanded ? <ChevronDown size={12} /> : <ChevronRight size={12} />}
            </button>
          )}
          {!hasChildren && <span style={{ width: '16px' }} />}

          <span style={{
            color: isSelected ? '#61dafb' : '#888',
            fontSize: '11px',
            fontWeight: '600',
            marginRight: '6px',
            textTransform: 'uppercase'
          }}>
            {widget.type}
          </span>

          <span style={{
            flex: 1,
            overflow: 'hidden',
            textOverflow: 'ellipsis',
            whiteSpace: 'nowrap',
            fontSize: '11px'
          }}>
            {getWidgetLabel(widget)}
          </span>
        </div>

        {hasChildren && isExpanded && (
          <div>
            {(widget as any).widgets.map((child: Widget, childIndex: number) =>
              renderWidget(child, depth + 1, `${path}.${childIndex}`, pageId, isTopLayerSection)
            )}
          </div>
        )}
      </div>
    );
  };

  return (
    <div
      style={{
        width: '260px',
        backgroundColor: '#1e1e1e',
        borderRight: '1px solid #333',
        overflowY: 'auto',
        overflowX: 'hidden',
        display: 'flex',
        flexDirection: 'column'
      }}
    >
      <div style={{
        padding: '12px',
        borderBottom: '1px solid #333',
        display: 'flex',
        alignItems: 'center',
        gap: '8px',
        color: '#fff',
        fontSize: '13px',
        fontWeight: '600'
      }}>
        <Layers size={16} />
        Page Structure
      </div>

      <div style={{ flex: 1 }}>
        {config.pages.map((page) => {
          const isExpanded = expandedPages.has(page.id);
          const isActive = currentPageId === page.id;

          return (
            <div key={page.id}>
              <div
                onClick={() => handlePageClick(page.id)}
                style={{
                  display: 'flex',
                  alignItems: 'center',
                  padding: '8px',
                  cursor: 'pointer',
                  backgroundColor: isActive ? '#2c2c2c' : 'transparent',
                  borderLeft: isActive ? '3px solid #007acc' : '3px solid transparent',
                  color: isActive ? '#fff' : '#ccc',
                  fontSize: '13px',
                  fontWeight: '500',
                  transition: 'all 0.15s ease'
                }}
                onMouseEnter={(e) => {
                  if (!isActive) {
                    e.currentTarget.style.backgroundColor = '#252526';
                  }
                }}
                onMouseLeave={(e) => {
                  if (!isActive) {
                    e.currentTarget.style.backgroundColor = 'transparent';
                  }
                }}
              >
                <button
                  onClick={(e) => {
                    e.stopPropagation();
                    togglePage(page.id);
                  }}
                  style={{
                    background: 'none',
                    border: 'none',
                    color: '#888',
                    cursor: 'pointer',
                    padding: '0 4px 0 0',
                    display: 'flex',
                    alignItems: 'center'
                  }}
                >
                  {isExpanded ? <ChevronDown size={14} /> : <ChevronRight size={14} />}
                </button>

                <span style={{ flex: 1 }}>{page.id}</span>
                <span style={{
                  fontSize: '10px',
                  color: '#666',
                  backgroundColor: '#2c2c2c',
                  padding: '2px 6px',
                  borderRadius: '3px'
                }}>
                  {page.widgets.length}
                </span>
              </div>

              {isExpanded && page.widgets.length > 0 && (
                <div style={{ marginLeft: '8px' }}>
                  {page.widgets.map((widget, index) => renderWidget(widget, 0, `${index}`, page.id))}
                </div>
              )}
            </div>
          );
        })}

        {config.top_layer && config.top_layer.widgets.length > 0 && (
          <>
            <div style={{ height: '1px', backgroundColor: '#333', margin: '8px 0' }} />
            <div>
              <div
                style={{
                  display: 'flex',
                  alignItems: 'center',
                  padding: '8px',
                  color: '#ccc',
                  fontSize: '13px',
                  fontWeight: '500'
                }}
              >
                <span style={{ flex: 1 }}>Top Layer</span>
                <span style={{
                  fontSize: '10px',
                  color: '#666',
                  backgroundColor: '#2c2c2c',
                  padding: '2px 6px',
                  borderRadius: '3px'
                }}>
                  {config.top_layer.widgets.length}
                </span>
              </div>
              <div style={{ marginLeft: '8px' }}>
                {config.top_layer.widgets.map((widget, index) => renderWidget(widget, 0, `${index}`, currentPageId, true))}
              </div>
            </div>
          </>
        )}
      </div>
    </div>
  );
};
