import React, { useState } from 'react';
import { Widget } from '../types/widgets';
import { ChevronRight, ChevronDown, Plus, Trash2 } from 'lucide-react';
import { WIDGET_CONFIGS } from '../config/widgetConfigs';

interface WidgetTreeProps {
  widgets: Widget[];
  selectedWidgetPath: string | null;
  onSelectWidget: (path: string) => void;
  onAddWidget: (parentPath: string, widgetType: string) => void;
  onDeleteWidget: (path: string) => void;
  parentPath?: string;
}

export const WidgetTree: React.FC<WidgetTreeProps> = ({
  widgets,
  selectedWidgetPath,
  onSelectWidget,
  onAddWidget,
  onDeleteWidget,
  parentPath = ''
}) => {
  const [expandedNodes, setExpandedNodes] = useState<Set<string>>(new Set());
  const [showAddMenu, setShowAddMenu] = useState<string | null>(null);

  const getWidgetMetaLabel = (widget: Widget) => {
    if (widget.id && !(widget as any)._autoGeneratedId) {
      return `#${widget.id}`;
    }
    if (widget.type === 'label' && (widget as any).text) {
      return `"${(widget as any).text}"`;
    }
    if (widget.type === 'checkbox' && (widget as any).text) {
      return `"${(widget as any).text}"`;
    }
    return null;
  };

  const toggleExpand = (path: string) => {
    const newExpanded = new Set(expandedNodes);
    if (newExpanded.has(path)) {
      newExpanded.delete(path);
    } else {
      newExpanded.add(path);
    }
    setExpandedNodes(newExpanded);
  };

  const renderWidget = (widget: Widget, index: number) => {
    const widgetPath = parentPath ? `${parentPath}.${index}` : `${index}`;
    const hasChildren = widget.type === 'obj' && (widget as any).widgets?.length > 0;
    const isExpanded = expandedNodes.has(widgetPath);
    const isSelected = selectedWidgetPath === widgetPath;

    return (
      <div key={widgetPath} style={{ marginLeft: parentPath ? '16px' : '0' }}>
        <div
          style={{
            display: 'flex',
            alignItems: 'center',
            padding: '6px 8px',
            backgroundColor: isSelected ? '#2a4a6a' : 'transparent',
            borderRadius: '4px',
            cursor: 'pointer',
            marginBottom: '2px',
            border: isSelected ? '1px solid #4a8aba' : '1px solid transparent'
          }}
          onMouseEnter={(e) => {
            if (!isSelected) {
              e.currentTarget.style.backgroundColor = '#2c2c2c';
            }
          }}
          onMouseLeave={(e) => {
            if (!isSelected) {
              e.currentTarget.style.backgroundColor = 'transparent';
            }
          }}
          onClick={() => onSelectWidget(widgetPath)}
        >
          {hasChildren && (
            <button
              onClick={(e) => {
                e.stopPropagation();
                toggleExpand(widgetPath);
              }}
              style={{
                background: 'none',
                border: 'none',
                color: '#aaa',
                cursor: 'pointer',
                padding: '0 4px',
                display: 'flex',
                alignItems: 'center'
              }}
            >
              {isExpanded ? <ChevronDown size={14} /> : <ChevronRight size={14} />}
            </button>
          )}
          {!hasChildren && <div style={{ width: '22px' }} />}
          
          <div style={{ flex: 1, display: 'flex', alignItems: 'center', gap: '8px' }}>
            <span style={{
              color: '#61dafb',
              fontSize: '12px',
              fontWeight: 500
            }}>
              {widget.type}
            </span>
            {getWidgetMetaLabel(widget) && (
              <span style={{
                color: '#aaa',
                fontSize: '11px',
                fontStyle: 'italic'
              }}>
                {getWidgetMetaLabel(widget)}
              </span>
            )}
          </div>

          {widget.type === 'obj' && (
            <button
              onClick={(e) => {
                e.stopPropagation();
                setShowAddMenu(showAddMenu === widgetPath ? null : widgetPath);
              }}
              style={{
                background: 'none',
                border: 'none',
                color: '#4a8aba',
                cursor: 'pointer',
                padding: '4px',
                display: 'flex',
                alignItems: 'center'
              }}
              title="Add child widget"
            >
              <Plus size={14} />
            </button>
          )}

          <button
            onClick={(e) => {
              e.stopPropagation();
              if (confirm(`Delete ${widget.type}${widget.id ? ` #${widget.id}` : ''}?`)) {
                onDeleteWidget(widgetPath);
              }
            }}
            style={{
              background: 'none',
              border: 'none',
              color: '#dc3545',
              cursor: 'pointer',
              padding: '4px',
              display: 'flex',
              alignItems: 'center'
            }}
            title="Delete widget"
          >
            <Trash2 size={12} />
          </button>
        </div>

        {showAddMenu === widgetPath && (
          <div
            style={{
              marginLeft: '32px',
              marginTop: '4px',
              marginBottom: '8px',
              padding: '8px',
              backgroundColor: '#1a1a1a',
              borderRadius: '4px',
              border: '1px solid #444',
              maxHeight: '200px',
              overflowY: 'auto'
            }}
          >
            <div style={{ fontSize: '11px', color: '#888', marginBottom: '6px' }}>Add widget:</div>
            <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '4px' }}>
              {WIDGET_CONFIGS.map(config => (
                <button
                  key={config.type}
                  onClick={(e) => {
                    e.stopPropagation();
                    onAddWidget(widgetPath, config.type);
                    setShowAddMenu(null);
                    setExpandedNodes(new Set([...expandedNodes, widgetPath]));
                  }}
                  style={{
                    padding: '6px 8px',
                    backgroundColor: '#2c2c2c',
                    border: '1px solid #444',
                    borderRadius: '4px',
                    color: '#fff',
                    fontSize: '11px',
                    cursor: 'pointer',
                    textAlign: 'left'
                  }}
                >
                  {config.label}
                </button>
              ))}
            </div>
          </div>
        )}

        {hasChildren && isExpanded && (
          <WidgetTree
            widgets={(widget as any).widgets}
            selectedWidgetPath={selectedWidgetPath}
            onSelectWidget={onSelectWidget}
            onAddWidget={onAddWidget}
            onDeleteWidget={onDeleteWidget}
            parentPath={widgetPath}
          />
        )}
      </div>
    );
  };

  return (
    <div style={{ fontSize: '12px' }}>
      {widgets.map((widget, index) => renderWidget(widget, index))}
    </div>
  );
};
