// LVGL Widget Types
export type WidgetType = 'label' | 'button' | 'slider' | 'switch' | 'checkbox' | 'arc' | 'bar' | 'spinner' | 'line' | 'image' | 'textarea' | 'dropdown' | 'roller' | 'obj' | 'buttonmatrix' | 'meter' | 'led' | 'spinbox' | 'msgbox';

export interface Position {
  x: number;
  y: number;
}

export interface Size {
  width: number;
  height: number;
}

export interface Color {
  r: number;
  g: number;
  b: number;
}

// Base widget interface
export interface BaseWidget {
  id?: string;
  type: WidgetType;
  x: number;
  y: number;
  width?: number | string;  // Can be number or "SIZE_CONTENT" or percentage
  height?: number | string; // Can be number or "SIZE_CONTENT" or percentage
  min_width?: number | string;
  min_height?: number | string;
  bg_color?: Color;
  border_color?: Color;
  border_width?: number;
  radius?: number;
  opacity?: number;
  hidden?: boolean;
  align?: string;
  styles?: string;
  text_font?: string;
  text_align?: string;
  text_letter_space?: number;
  text_line_space?: number;
  layout?: string;  // LVGL layout type: FLEX, GRID, etc.
  flex_flow?: string;  // For flex layout: ROW, COLUMN, etc.
  flex_align?: string;  // Flex alignment
  grid_rows?: any[];  // Grid template rows
  grid_cols?: any[];  // Grid template columns
  pad_all?: number;
  pad_top?: number;
  pad_right?: number;
  pad_bottom?: number;
  pad_left?: number;
  _measuredWidth?: number;
  _measuredHeight?: number;
  _explicitWidth?: boolean;
  _explicitHeight?: boolean;
  _autoGeneratedId?: boolean;
  _styleApplied?: string[];
}

// Specific widget interfaces
export interface LabelWidget extends BaseWidget {
  type: 'label';
  text: string;
  text_color?: Color;
}

export interface ButtonWidget extends BaseWidget {
  type: 'button';
  checkable?: boolean;
  on_click?: string;
  widgets?: Widget[];  // Child widgets (like labels)
}

export interface SliderWidget extends BaseWidget {
  type: 'slider';
  min_value?: number;
  max_value?: number;
  value?: number;
  animated?: boolean;
  on_value?: string;
}

export interface SwitchWidget extends BaseWidget {
  type: 'switch';
  checked?: boolean;
  on_value?: string;
}

export interface CheckboxWidget extends BaseWidget {
  type: 'checkbox';
  text?: string;
  checked?: boolean;
  on_value?: string;
}

export interface ArcWidget extends BaseWidget {
  type: 'arc';
  min_value?: number;
  max_value?: number;
  value?: number;
  start_angle?: number;
  end_angle?: number;
  rotation?: number;
}

export interface BarWidget extends BaseWidget {
  type: 'bar';
  min_value?: number;
  max_value?: number;
  value?: number;
  animated?: boolean;
}

export interface SpinnerWidget extends BaseWidget {
  type: 'spinner';
  arc_length?: number;
  spin_time?: number;
}

export interface LineWidget extends BaseWidget {
  type: 'line';
  points?: Array<[number, number]>;
  line_color?: Color;
  line_width?: number;
  line_dash_width?: number;
  line_dash_gap?: number;
  line_rounded?: boolean;
}

export interface ObjWidget extends BaseWidget {
  type: 'obj';
  widgets?: Widget[];
  pad_all?: number;
  pad_row?: number;
  pad_column?: number;
  bg_opa?: string;
  border_opa?: string;
}

export interface ImageWidget extends BaseWidget {
  type: 'image';
  src?: string;
}

export interface TextAreaWidget extends BaseWidget {
  type: 'textarea';
  text?: string;
  placeholder?: string;
  one_line?: boolean;
  password_mode?: boolean;
  max_length?: number;
}

export interface DropdownWidget extends BaseWidget {
  type: 'dropdown';
  options?: string[];
  selected?: number;
  on_value?: string;
}

export interface RollerWidget extends BaseWidget {
  type: 'roller';
  options?: string[];
  selected?: number;
  visible_row_count?: number;
  on_value?: string;
}

export interface ButtonMatrixWidget extends BaseWidget {
  type: 'buttonmatrix';
  rows?: Array<{
    buttons: Array<{
      id?: string;
      text: string;
      width?: number;
    }>;
  }>;
  items?: {
    styles?: string;
  };
  one_checked?: boolean;
}

export interface MeterWidget extends BaseWidget {
  type: 'meter';
  scales?: any[];
}

export interface LedWidget extends BaseWidget {
  type: 'led';
  color?: Color;
  brightness?: number;
}

export interface SpinboxWidget extends BaseWidget {
  type: 'spinbox';
  value?: number;
  range_from?: number;
  range_to?: number;
  step?: number;
  rollover?: boolean;
  digit_count?: number;
  decimal_places?: number;
}

export interface MsgBoxWidget extends BaseWidget {
  type: 'msgbox';
  title?: string;
  text?: string;
  close_button?: boolean;
  buttons?: string[];
}

// Union type for all widgets
export type Widget = 
  | LabelWidget 
  | ButtonWidget 
  | SliderWidget 
  | SwitchWidget 
  | CheckboxWidget 
  | ArcWidget 
  | BarWidget 
  | SpinnerWidget 
  | LineWidget 
  | ObjWidget
  | ImageWidget 
  | TextAreaWidget 
  | DropdownWidget 
  | RollerWidget
  | ButtonMatrixWidget
  | MeterWidget
  | LedWidget
  | SpinboxWidget
  | MsgBoxWidget;

// Page interface
export interface Page {
  id: string;
  widgets: Widget[];
  page_wrap?: boolean;  // Whether page wraps in navigation
  layout?: string;  // Page layout type
  skip?: boolean;  // Whether to skip page in navigation
}

// Style definition interface
export interface StyleDefinition {
  id: string;
  text_color?: Color;
  text_font?: string;
  text_letter_space?: number;
  text_line_space?: number;
  bg_color?: Color;
  bg_grad_color?: Color;
  bg_grad_dir?: string;
  bg_opa?: string;
  border_color?: Color;
  border_width?: number;
  border_opa?: string;
  radius?: number;
  pad_all?: number;
  pad_top?: number;
  pad_right?: number;
  pad_bottom?: number;
  pad_left?: number;
  pad_row?: number;
  pad_column?: number;
  width?: string | number;
  height?: string | number;
  text_align?: string;
  align?: string;
  [key: string]: any; // Allow other style properties
}

// Top layer interface
export interface TopLayer {
  widgets: Widget[];
}

// Font definition interface
export interface FontGlyph {
  file?: string;
  glyphs?: string[];
}

export interface FontDefinition {
  file: string;
  id: string;
  size: number;
  extras?: FontGlyph[];
  bpp?: number;
  [key: string]: any; // Allow other font properties
}

// Complete configuration
export interface LVGLConfig {
  pages: Page[];
  style_definitions?: StyleDefinition[];
  fonts?: FontDefinition[];
  top_layer?: TopLayer;
  bg_color?: string | number;  // LVGL background color (hex format)
}

// Widget configuration for the palette
export interface WidgetConfig {
  type: WidgetType;
  label: string;
  icon: string;
  defaultProps: Partial<Widget>;
}

// Severity of a compatibility issue
export type IssueSeverity = 'error' | 'warning' | 'info';

// Compatibility issue found when importing a full ESPHome file
export interface CompatibilityIssue {
  severity: IssueSeverity;
  category: string;
  message: string;
  detail?: string;
}

// Result of importing a full ESPHome file
export interface ESPHomeImportResult {
  lvglConfig: LVGLConfig;
  /** Original raw YAML string – used to reconstruct the full file on export */
  rawEsphomeYaml: string;
  /** Whether the input looked like a full ESPHome file (has esphome:/esp32:/etc.) */
  isFullFile: boolean;
  issues: CompatibilityIssue[];
}
