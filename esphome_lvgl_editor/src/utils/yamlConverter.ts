/**
 * Returns true if the YAML string looks like a full ESPHome device file
 * (i.e. it contains top-level keys other than lvgl/pages/style_definitions/font)
 */
export const isFullESPHomeYaml = (raw: string): boolean => {
  const fullFileKeys = /^\s*(esphome|esp32|esp8266|rp2040|api|ota|wifi|mqtt|globals|script|interval|time|sensor|binary_sensor|text_sensor|display|spi|i2c|sx1509|packages|substitutions|logger)\s*:/m;
  return fullFileKeys.test(raw);
};

/**
 * Extract the `lvgl:` block from a raw ESPHome YAML string.
 * Returns the block with leading indentation stripped, plus the indent level.
 */
export const extractLvglSection = (raw: string): { lvglYaml: string; indent: number; startLine: number; endLine: number } => {
  const lines = raw.split('\n');
  let lvglStart = -1;
  let lvglIndent = 0;

  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(/^(\s*)lvgl:\s*$/);
    if (m) { lvglStart = i; lvglIndent = m[1].length; break; }
  }

  if (lvglStart === -1) return { lvglYaml: '', indent: 0, startLine: -1, endLine: -1 };

  let lvglEnd = lines.length;
  for (let i = lvglStart + 1; i < lines.length; i++) {
    const line = lines[i];
    if (line.trim() === '' || line.trim().startsWith('#')) continue;
    const li = line.search(/\S/);
    if (li !== -1 && li <= lvglIndent) { lvglEnd = i; break; }
  }

  const block = lines.slice(lvglStart, lvglEnd).map(l =>
    l.startsWith(' '.repeat(lvglIndent)) ? l.slice(lvglIndent) : l
  );

  return { lvglYaml: block.join('\n'), indent: lvglIndent, startLine: lvglStart, endLine: lvglEnd };
};

/**
 * Analyse a parsed LVGL config + raw ESPHome sections and return a list of
 * features that are not fully supported by the visual editor.
 */
export const analyzeCompatibility = (raw: string, lvglConfig: LVGLConfig): CompatibilityIssue[] => {
  const issues: CompatibilityIssue[] = [];

  // ── Non-LVGL sections that are silently preserved ──
  const ignoredSections: Array<[RegExp, string]> = [
    [/^\s*substitutions\s*:/m,  'substitutions'],
    [/^\s*packages\s*:/m,       'packages (!include)'],
    [/^\s*globals\s*:/m,        'globals'],
    [/^\s*script\s*:/m,         'script'],
    [/^\s*interval\s*:/m,       'interval'],
    [/^\s*sx1509\s*:/m,         'sx1509 (keypad)'],
    [/^\s*spi\s*:/m,            'spi'],
    [/^\s*i2c\s*:/m,            'i2c'],
    [/^\s*api\s*:/m,            'api'],
    [/^\s*time\s*:/m,           'time'],
    [/^\s*text_sensor\s*:/m,    'text_sensor'],
    [/^\s*binary_sensor\s*:/m,  'binary_sensor'],
    [/^\s*sensor\s*:/m,         'sensor'],
  ];
  for (const [re, name] of ignoredSections) {
    if (re.test(raw)) {
      issues.push({ severity: 'info', category: 'Preserved section', message: `Section "${name}" is preserved as-is and cannot be edited visually.` });
    }
  }

  // ── ESPHome-specific YAML tags ──
  if (/!secret\s/m.test(raw))  issues.push({ severity: 'info',    category: 'YAML tags', message: '!secret tags are preserved but not editable in the UI.' });
  if (/!include\s/m.test(raw)) issues.push({ severity: 'info',    category: 'YAML tags', message: '!include tags are preserved but not editable in the UI.' });
  if (/!lambda\s/m.test(raw))  issues.push({ severity: 'warning', category: 'YAML tags', message: '!lambda values in scripts/callbacks are preserved but dynamic runtime behaviour is not simulated in the preview.' });

  // ── LVGL-specific checks ──
  const checkWidgets = (widgets: Widget[], context: string) => {
    for (const w of widgets) {
      if (w.type === 'meter') {
        issues.push({ severity: 'warning', category: 'Widget', message: `"meter" widget (id: ${w.id || 'unnamed'}) – scales and indicator hands are not editable visually; displayed as a placeholder.`, detail: context });
      }
      if ((w as any).on_press || (w as any).on_click || (w as any).on_value) {
        issues.push({ severity: 'info', category: 'Widget events', message: `Widget ${w.id ? '"' + w.id + '"' : '(unnamed)'} has event handlers (on_press/on_click/on_value) that are preserved but not editable.`, detail: context });
      }
      if (typeof w.x === 'number' && w.x < 0) {
        issues.push({ severity: 'info', category: 'Coordinates', message: `Widget ${w.id ? '"' + w.id + '"' : '(unnamed)'} has negative x (${w.x}) for right-alignment; canvas shows it at absolute position.` });
      }
      if (typeof w.y === 'number' && w.y < 0) {
        issues.push({ severity: 'info', category: 'Coordinates', message: `Widget ${w.id ? '"' + w.id + '"' : '(unnamed)'} has negative y (${w.y}) for bottom-alignment; canvas shows it at absolute position.` });
      }
      if ((w as any).widgets) checkWidgets((w as any).widgets, context);
    }
  };

  for (const page of lvglConfig.pages) checkWidgets(page.widgets, `page "${page.id}"`);
  if (lvglConfig.top_layer) checkWidgets(lvglConfig.top_layer.widgets, 'top_layer');

  // ── lvgl meta properties we don't edit ──
  const lvglMetaKeys = ['displays', 'touchscreens', 'color_depth', 'byte_order'];
  const { lvglYaml } = extractLvglSection(raw);
  if (lvglYaml) {
    try {
      const lvglParsed = yaml.load(lvglYaml, { schema: ESP_HOME_SCHEMA }) as any;
      const lvgl = lvglParsed?.lvgl || lvglParsed || {};
      for (const k of lvglMetaKeys) {
        if (lvgl[k] !== undefined) {
          issues.push({ severity: 'info', category: 'LVGL config', message: `LVGL property "${k}" is preserved but not editable in the UI.` });
        }
      }
    } catch { /* ignore */ }
  }

  // Deduplicate exact-same messages
  const seen = new Set<string>();
  return issues.filter(i => { const k = i.message; if (seen.has(k)) return false; seen.add(k); return true; });
};

/**
 * Attempt to parse a full ESPHome YAML file.
 * Extracts only the `lvgl:` section for visual editing; everything else is kept
 * verbatim so it can be reconstructed on export.
 */
export const parseFullESPHomeFile = (raw: string): ESPHomeImportResult => {
  const isFullFile = isFullESPHomeYaml(raw);

  if (!isFullFile) {
    // Plain LVGL-only YAML – use existing parser
    const lvglConfig = yamlToConfig(raw);
    return { lvglConfig, rawEsphomeYaml: raw, isFullFile: false, issues: [] };
  }

  const { lvglYaml } = extractLvglSection(raw);

  let lvglConfig: LVGLConfig = { pages: [{ id: 'main_page', widgets: [] }] };

  if (lvglYaml) {
    try {
      // The extracted block already starts at column 0 with `lvgl:`
      lvglConfig = yamlToConfig(lvglYaml);
    } catch (e) {
      console.warn('Could not parse extracted lvgl section:', e);
    }
  }

  // Also try to pull font definitions from the top-level `font:` section
  // (they are referenced by LVGL widgets but live outside lvgl:)
  if (!lvglConfig.fonts || lvglConfig.fonts.length === 0) {
    try {
      // Temporarily parse just the font section via regex extraction
      const fontMatch = raw.match(/^(\s*)font:\s*\n((?:\1  [^\n]*\n?)+)/m);
      if (fontMatch) {
        const indent = fontMatch[1].length;
        const fontBlock = fontMatch[0].split('\n').map(l =>
          l.startsWith(' '.repeat(indent)) ? l.slice(indent) : l
        ).join('\n');
        try {
          const parsed = yaml.load(fontBlock, { schema: ESP_HOME_SCHEMA }) as any;
          if (parsed?.font) lvglConfig = { ...lvglConfig, fonts: parsed.font };
        } catch { /* pass */ }
      }
    } catch { /* pass */ }
  }

  const issues = analyzeCompatibility(raw, lvglConfig);
  return { lvglConfig, rawEsphomeYaml: raw, isFullFile: true, issues };
};

/**
 * Reconstruct a full ESPHome YAML string by replacing the `lvgl:` block
 * with a freshly-generated one from the current visual-editor config.
 *
 * Properties that are stored in the visual config (style_definitions, fonts,
 * pages, top_layer) replace what was in the original lvgl: section.  All other
 * top-level keys (substitutions, esp32, globals, script, …) are left untouched.
 */
export const reconstructFullESPHomeYaml = (rawEsphomeYaml: string, lvglConfig: LVGLConfig): string => {
  const { lvglYaml, indent, startLine, endLine } = extractLvglSection(rawEsphomeYaml);

  if (startLine === -1) {
    // No lvgl: section found – just return the original + appended lvgl section
    const newLvgl = configToPagesYaml(lvglConfig);
    return rawEsphomeYaml.trimEnd() + '\n\nlvgl:\n' + newLvgl.split('\n').map(l => '  ' + l).join('\n');
  }

  // Preserve unknown lvgl: meta properties (displays, touchscreens, color_depth, etc.)
  let lvglMeta: Record<string, any> = {};
  try {
    const parsed = yaml.load(lvglYaml, { schema: ESP_HOME_SCHEMA }) as any;
    const lvgl = parsed?.lvgl || parsed || {};
    const knownKeys = new Set(['style_definitions', 'pages', 'top_layer', 'bg_color', 'font']);
    for (const k of Object.keys(lvgl)) {
      if (!knownKeys.has(k)) lvglMeta[k] = lvgl[k];
    }
  } catch { /* pass */ }

  // Build the new lvgl section content
  const lvglStructure: any = {};
  // Put meta keys first (displays, touchscreens, color_depth, byte_order)
  Object.assign(lvglStructure, lvglMeta);

  if (lvglConfig.bg_color !== undefined) {
    const bgColor = lvglConfig.bg_color as any;
    // bg_color may be stored as a Color {r,g,b} object due to parseColor() in yamlToConfig
    if (typeof bgColor === 'object' && 'r' in bgColor) {
      lvglStructure.bg_color = formatColor(bgColor);
    } else {
      lvglStructure.bg_color = bgColor;
    }
  }

  if (lvglConfig.style_definitions && lvglConfig.style_definitions.length > 0) {
    lvglStructure.style_definitions = lvglConfig.style_definitions.map(style => {
      const s: any = { id: style.id };
      if (style.text_color) s.text_color = formatColor(style.text_color);
      if (style.text_font)  s.text_font  = style.text_font;
      if (style.bg_color)      s.bg_color      = formatColor(style.bg_color);
      if (style.bg_grad_color) s.bg_grad_color = formatColor(style.bg_grad_color);
      if (style.bg_grad_dir)   s.bg_grad_dir   = style.bg_grad_dir;
      if (style.bg_opa)        s.bg_opa        = style.bg_opa;
      if (style.border_color)  s.border_color  = formatColor(style.border_color);
      if (style.border_width !== undefined) s.border_width = style.border_width;
      if (style.border_opa)    s.border_opa    = style.border_opa;
      if (style.radius !== undefined) s.radius = style.radius;
      if (style.pad_all !== undefined) s.pad_all = style.pad_all;
      if (style.pad_row !== undefined) s.pad_row = style.pad_row;
      if (style.pad_column !== undefined) s.pad_column = style.pad_column;
      if (style.width !== undefined)  s.width  = style.width;
      if (style.height !== undefined) s.height = style.height;
      if (style.text_align) s.text_align = style.text_align;
      if (style.align)      s.align      = style.align;
      Object.keys(style).forEach(k => { if (!s.hasOwnProperty(k) && k !== 'id') s[k] = (style as any)[k]; });
      return s;
    });
  }

  lvglStructure.pages = lvglConfig.pages.map(page => ({
    id: page.id,
    widgets: page.widgets.map(w => widgetToYaml(w))
  }));

  if (lvglConfig.top_layer && lvglConfig.top_layer.widgets.length > 0) {
    lvglStructure.top_layer = { widgets: lvglConfig.top_layer.widgets.map(w => widgetToYaml(w)) };
  }

  const newLvglContent = normalizeLvglSpacing(normalizeDumpedHexColors(yaml.dump({ lvgl: lvglStructure }, {
    indent: 2, lineWidth: -1, noRefs: true,
    quotingType: '"', forceQuotes: false, noCompatMode: true,
    allowUnicode: false
  } as any)));

  // Re-indent to match original file's indent level
  const indentStr = ' '.repeat(indent);
  const reindented = newLvglContent.split('\n').map(l => l ? indentStr + l : l).join('\n');

  const lines = rawEsphomeYaml.split('\n');
  const before = lines.slice(0, startLine).join('\n');
  const after  = lines.slice(endLine).join('\n');

  return (before ? before + '\n' : '') + reindented.trimEnd() + (after ? '\n' + after : '');
};

export interface ReconstructionValidation {
  ok: boolean;
  error?: string;
}

/**
 * Sanity-check the output of reconstructFullESPHomeYaml() against the file it
 * came from, BEFORE it is ever written to disk. Guards against the editor
 * silently corrupting or truncating a real device config: invalid YAML, a
 * suspiciously large shrink, or a top-level section (wifi:, esp32:, …) that
 * went missing.
 */
export const validateReconstruction = (original: string, reconstructed: string): ReconstructionValidation => {
  if (!reconstructed.trim()) {
    return { ok: false, error: 'Result is empty.' };
  }

  try {
    yaml.load(reconstructed, { schema: ESP_HOME_SCHEMA });
  } catch (e) {
    return { ok: false, error: 'Result is not valid YAML: ' + (e instanceof Error ? e.message : String(e)) };
  }

  if (original.length > 200 && reconstructed.length < original.length * 0.5) {
    return {
      ok: false,
      error: `Result is suspiciously short (${reconstructed.length} vs original ${original.length} characters).`
    };
  }

  // Every top-level (column-0) key present in the original, other than lvgl:,
  // must still be present after reconstruction.
  const topLevelKeyRe = /^([A-Za-z_][\w-]*)\s*:/gm;
  const originalKeys = new Set<string>();
  let match: RegExpExecArray | null;
  while ((match = topLevelKeyRe.exec(original)) !== null) {
    originalKeys.add(match[1]);
  }
  originalKeys.delete('lvgl');

  const missing: string[] = [];
  for (const key of originalKeys) {
    if (!new RegExp(`^${key}\\s*:`, 'm').test(reconstructed)) missing.push(key);
  }
  if (missing.length > 0) {
    return { ok: false, error: `Top-level section(s) missing after reconstruction: ${missing.join(', ')}` };
  }

  return { ok: true };
};
