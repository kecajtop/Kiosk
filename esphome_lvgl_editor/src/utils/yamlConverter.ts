// Export just the pages section (more flexible)
export const configToPagesYaml = (config: LVGLConfig): string => {
  const structure: any = {};
  
  // Add font definitions if present
  if (config.fonts && config.fonts.length > 0) {
    structure.font = config.fonts.map(font => {
      const fontObj: any = {
        file: font.file,
        id: font.id,
        size: font.size
      };
      
      if (font.extras) fontObj.extras = font.extras;
      if (font.bpp !== undefined) fontObj.bpp = font.bpp;
      
      // Add any other properties
      Object.keys(font).forEach(key => {
        if (!fontObj.hasOwnProperty(key) && key !== 'file' && key !== 'id' && key !== 'size') {
          fontObj[key] = font[key];
        }
      });
      
      return fontObj;
    });
  }
  
  // Add style_definitions if present
  if (config.style_definitions && config.style_definitions.length > 0) {
    structure.style_definitions = config.style_definitions.map(style => {
      const styleObj: any = { id: style.id };
      if (style.text_color) styleObj.text_color = formatColor(style.text_color);
      if (style.text_font) styleObj.text_font = style.text_font;
      if (style.bg_color) styleObj.bg_color = formatColor(style.bg_color);
      if (style.bg_grad_color) styleObj.bg_grad_color = formatColor(style.bg_grad_color);
      if (style.bg_grad_dir) styleObj.bg_grad_dir = style.bg_grad_dir;
      if (style.bg_opa) styleObj.bg_opa = style.bg_opa;
      if (style.border_color) styleObj.border_color = formatColor(style.border_color);
      if (style.border_width !== undefined) styleObj.border_width = style.border_width;
      if (style.border_opa) styleObj.border_opa = style.border_opa;
      if (style.radius !== undefined) styleObj.radius = style.radius;
      if (style.pad_all !== undefined) styleObj.pad_all = style.pad_all;
      if (style.pad_row !== undefined) styleObj.pad_row = style.pad_row;
      if (style.pad_column !== undefined) styleObj.pad_column = style.pad_column;
      if (style.width !== undefined) styleObj.width = style.width;
      if (style.height !== undefined) styleObj.height = style.height;
      if (style.text_align) styleObj.text_align = style.text_align;
      if (style.align) styleObj.align = style.align;
      
      // Add any other properties
      Object.keys(style).forEach(key => {
        if (!styleObj.hasOwnProperty(key) && key !== 'id') {
          styleObj[key] = (style as any)[key];
        }
      });
      
      return styleObj;
    });
  }
  
  // Add pages
  structure.pages = config.pages.map(page => ({
    id: page.id,
    widgets: page.widgets.map(widget => widgetToYaml(widget))
  }));
  
  // Add top_layer if present
  if (config.top_layer && config.top_layer.widgets.length > 0) {
    structure.top_layer = {
      widgets: config.top_layer.widgets.map(widget => widgetToYaml(widget))
    };
  }

  return normalizeLvglSpacing(normalizeDumpedHexColors(yaml.dump(structure, {
    indent: 2,
    lineWidth: -1,
    noRefs: true,
    quotingType: '"',
    forceQuotes: false,
    noCompatMode: true,
    allowUnicode: false
  } as any)));
};

