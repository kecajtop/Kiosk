// Custom YAML schema that tolerates ESPHome-specific tags (!secret, !lambda, !include)
// so importing a full ESPHome file never throws a "unknown tag" error.
const espHomeTypes = [
  new yaml.Type('!secret',  { kind: 'scalar', construct: (d: any) => `!secret ${d}` }),
  new yaml.Type('!include', { kind: 'scalar', construct: (d: any) => `!include ${d}` }),
  new yaml.Type('!lambda',  { kind: 'scalar', construct: (d: any) => d }),
  new yaml.Type('!extend',  { kind: 'scalar', construct: (d: any) => `!extend ${d}` }),
];
const ESP_HOME_SCHEMA = (yaml.DEFAULT_SCHEMA as any).extend(espHomeTypes);

// Helper function to format color for YAML
const formatColor = (color: Color | undefined): string | undefined => {
  if (color === undefined || color === null) return undefined;
  return `0x${color.r.toString(16).padStart(2, '0')}${color.g.toString(16).padStart(2, '0')}${color.b.toString(16).padStart(2, '0')}`;
};

// Format a raw numeric or string color value (from deep structures like meter scales) to hex string
const formatRawColor = (v: any): string => {
  if (typeof v === 'number') return '0x' + v.toString(16).padStart(6, '0');
  return v;
};

const normalizeDumpedHexColors = (yamlText: string): string => {
  return yamlText.replace(/"0x([0-9a-fA-F]+)"/g, (_match, hex) => `0x${String(hex).toUpperCase()}`);
};

const normalizeLvglSpacing = (yamlText: string): string => {
  return yamlText
    .replace(/(\n\s*touchscreens:\s*\[(?:[^\n]*)\]\n)(\s*color_depth:)/, '$1\n$2')
    .replace(/(\n\s*byte_order:\s*[^\n]+\n)(\s*bg_color:)/, '$1\n$2')
    .replace(/(\n\s*bg_color:\s*[^\n]+\n)(\s*style_definitions:)/, '$1\n$2')
    .replace(/(\n\s*style_definitions:\n(?:[\s\S]*?))(\n\s*pages:)/, '$1\n$2')
    .replace(/(\n\s*pages:\n(?:[\s\S]*?))(\n\s*top_layer:)/, '$1\n$2');
};

// Recursively walk an arbitrary object and convert numeric color field values to hex strings.
// Used for widgets like meter whose `scales` are stored raw.
const COLOR_FIELD_NAMES = new Set([
  'color', 'line_color', 'bg_color', 'bg_grad_color', 'border_color', 'text_color'
]);
const fixColorsDeep = (obj: any): any => {
  if (obj === null || obj === undefined || typeof obj !== 'object') return obj;
  if (Array.isArray(obj)) return obj.map(fixColorsDeep);
  const result: any = {};
  for (const [k, v] of Object.entries(obj)) {
    result[k] = COLOR_FIELD_NAMES.has(k) && typeof v === 'number' ? formatRawColor(v) : fixColorsDeep(v);
  }
  return result;
};

// Helper function to parse color from YAML
const parseColor = (colorStr: string | number | undefined): Color | undefined => {
  if (colorStr === undefined || colorStr === null) return undefined;
  
  // Convert to string if it's a number (handles 0x000000 parsed as integer 0)
  let hexStr = typeof colorStr === 'number' 
    ? '0x' + colorStr.toString(16).padStart(6, '0')
    : colorStr;
    
  // Remove 0x prefix if present
  const hex = hexStr.toString().replace('0x', '').padStart(6, '0');
  
  return {
    r: parseInt(hex.substring(0, 2), 16),
    g: parseInt(hex.substring(2, 4), 16),
    b: parseInt(hex.substring(4, 6), 16)
  };
};

// Convert internal widget to ESPHome YAML format
const widgetToYaml = (widget: Widget): any => {
  const baseProps: any = {};
  // Properties injected by applyStyleToWidget (canvas-only) – must NOT appear in export output
  const styleApplied = new Set<string>((widget as any)._styleApplied || []);
  const skip = (key: string) => styleApplied.has(key);

  // Only include ID if explicitly set (not auto-generated)
  if (widget.id && !(widget as any)._autoGeneratedId) {
    baseProps.id = widget.id;
  }

  if (widget.x !== undefined) baseProps.x = widget.x;
  if (widget.y !== undefined) baseProps.y = widget.y;

  // Only export width/height if they were explicitly set
  if (widget.width !== undefined && !skip('width') && (widget.width === 'SIZE_CONTENT' || (typeof widget.width === 'string' && widget.width.includes('%')) || (typeof widget.width === 'number' && (widget as any)._explicitWidth))) baseProps.width = widget.width;
  if (widget.height !== undefined && !skip('height') && (widget.height === 'SIZE_CONTENT' || (typeof widget.height === 'string' && widget.height.includes('%')) || (typeof widget.height === 'number' && (widget as any)._explicitHeight))) baseProps.height = widget.height;
  if (widget.bg_color      && !skip('bg_color'))      baseProps.bg_color      = formatColor(widget.bg_color);
  if ((widget as any).bg_grad_color && !skip('bg_grad_color')) baseProps.bg_grad_color = formatColor((widget as any).bg_grad_color);
  if ((widget as any).bg_grad_dir   && !skip('bg_grad_dir'))   baseProps.bg_grad_dir   = (widget as any).bg_grad_dir;
  if ((widget as any).bg_opa        && !skip('bg_opa'))        baseProps.bg_opa        = (widget as any).bg_opa;
  if (widget.border_color  && !skip('border_color'))  baseProps.border_color  = formatColor(widget.border_color);
  if (widget.border_width !== undefined && !skip('border_width')) baseProps.border_width = widget.border_width;
  if ((widget as any).border_opa    && !skip('border_opa'))    baseProps.border_opa    = (widget as any).border_opa;
  if (widget.radius !== undefined   && !skip('radius'))        baseProps.radius        = widget.radius;
  if ((widget as any).pad_all !== undefined && !skip('pad_all'))   baseProps.pad_all   = (widget as any).pad_all;
  if ((widget as any).pad_row !== undefined && !skip('pad_row'))   baseProps.pad_row   = (widget as any).pad_row;
  if ((widget as any).pad_column !== undefined && !skip('pad_column')) baseProps.pad_column = (widget as any).pad_column;
  if (widget.opacity !== undefined) baseProps.opacity = widget.opacity;
  if (widget.hidden !== undefined)  baseProps.hidden  = widget.hidden;
  if (widget.align    && !skip('align'))     baseProps.align     = widget.align;
  if (widget.styles)                         baseProps.styles    = widget.styles;
  if (widget.text_font  && !skip('text_font'))  baseProps.text_font  = widget.text_font;
  if (widget.text_align && !skip('text_align')) baseProps.text_align = widget.text_align;
  if ((widget as any).text_color && !skip('text_color')) baseProps.text_color = formatColor((widget as any).text_color);

  const result: any = {};

  switch (widget.type) {
    case 'label':
      result.label = {
        ...baseProps
      };
      if (widget.text !== undefined) result.label.text = widget.text;
      break;

    case 'button':
      result.button = {
        ...baseProps
      };
      if (widget.checkable !== undefined) result.button.checkable = widget.checkable;
      if (widget.on_click) result.button.on_click = widget.on_click;
      if (widget.widgets && widget.widgets.length > 0) {
        result.button.widgets = widget.widgets.map(w => widgetToYaml(w));
      }
      break;

    case 'slider':
      result.slider = {
        ...baseProps
      };
      if (widget.min_value !== undefined) result.slider.min_value = widget.min_value;
      if (widget.max_value !== undefined) result.slider.max_value = widget.max_value;
      if (widget.value !== undefined) result.slider.value = widget.value;
      if (widget.animated !== undefined) result.slider.animated = widget.animated;
      if (widget.on_value) result.slider.on_value = widget.on_value;
      break;

    case 'switch':
      result.switch = {
        ...baseProps
      };
      if (widget.checked !== undefined) result.switch.checked = widget.checked;
      if (widget.on_value) result.switch.on_value = widget.on_value;
      break;

    case 'checkbox':
      result.checkbox = {
        ...baseProps
      };
      if (widget.text) result.checkbox.text = widget.text;
      if (widget.checked !== undefined) result.checkbox.checked = widget.checked;
      if (widget.on_value) result.checkbox.on_value = widget.on_value;
      break;

    case 'arc':
      result.arc = {
        ...baseProps
      };
      if (widget.min_value !== undefined) result.arc.min_value = widget.min_value;
      if (widget.max_value !== undefined) result.arc.max_value = widget.max_value;
      if (widget.value !== undefined) result.arc.value = widget.value;
      if (widget.start_angle !== undefined) result.arc.start_angle = widget.start_angle;
      if (widget.end_angle !== undefined) result.arc.end_angle = widget.end_angle;
      if (widget.rotation !== undefined) result.arc.rotation = widget.rotation;
      break;

    case 'bar':
      result.bar = {
        ...baseProps
      };
      if (widget.min_value !== undefined) result.bar.min_value = widget.min_value;
      if (widget.max_value !== undefined) result.bar.max_value = widget.max_value;
      if (widget.value !== undefined) result.bar.value = widget.value;
      if (widget.animated !== undefined) result.bar.animated = widget.animated;
      break;

    case 'spinner':
      result.spinner = {
        ...baseProps
      };
      if (widget.arc_length !== undefined) result.spinner.arc_length = widget.arc_length;
      if (widget.spin_time !== undefined) result.spinner.spin_time = widget.spin_time;
      break;

    case 'line':
      // For line widgets, only include specific line properties
      result.line = {};
      if (widget.id && !(widget as any)._autoGeneratedId) result.line.id = widget.id;
      if (widget.points) {
        // Convert points array to YAML format
        result.line.points = widget.points.map(point => `${point[0]}, ${point[1]}`);
      }
      if (widget.line_color) result.line.line_color = formatColor(widget.line_color);
      if (widget.line_width !== undefined) result.line.line_width = widget.line_width;
      if ((widget as any).line_dash_width !== undefined) result.line.line_dash_width = (widget as any).line_dash_width;
      if ((widget as any).line_dash_gap !== undefined) result.line.line_dash_gap = (widget as any).line_dash_gap;
      if ((widget as any).line_rounded !== undefined) result.line.line_rounded = (widget as any).line_rounded;
      break;

    case 'obj':
      result.obj = {
        ...baseProps
      };
      if (widget.widgets && widget.widgets.length > 0) {
        result.obj.widgets = widget.widgets.map(w => widgetToYaml(w));
      }
      break;

    case 'image':
      result.image = {
        ...baseProps
      };
      if (widget.src) result.image.src = widget.src;
      break;

    case 'textarea':
      result.textarea = {
        ...baseProps
      };
      if (widget.text) result.textarea.text = widget.text;
      if (widget.placeholder) result.textarea.placeholder = widget.placeholder;
      if (widget.one_line !== undefined) result.textarea.one_line = widget.one_line;
      if (widget.password_mode !== undefined) result.textarea.password_mode = widget.password_mode;
      if (widget.max_length !== undefined) result.textarea.max_length = widget.max_length;
      break;

    case 'dropdown':
      result.dropdown = {
        ...baseProps
      };
      if (widget.options) result.dropdown.options = widget.options;
      if (widget.selected !== undefined) result.dropdown.selected = widget.selected;
      if (widget.on_value) result.dropdown.on_value = widget.on_value;
      break;

    case 'roller':
      result.roller = {
        ...baseProps
      };
      if (widget.options) result.roller.options = widget.options;
      if (widget.selected !== undefined) result.roller.selected = widget.selected;
      if (widget.visible_row_count !== undefined) result.roller.visible_row_count = widget.visible_row_count;
      if (widget.on_value) result.roller.on_value = widget.on_value;
      break;

    case 'buttonmatrix':
      result.buttonmatrix = {
        ...baseProps
      };
      if ((widget as any).rows) result.buttonmatrix.rows = (widget as any).rows;
      if ((widget as any).items) result.buttonmatrix.items = (widget as any).items;
      if ((widget as any).one_checked !== undefined) result.buttonmatrix.one_checked = (widget as any).one_checked;
      if ((widget as any).outline_width !== undefined) result.buttonmatrix.outline_width = (widget as any).outline_width;
      break;

    case 'meter':
      result.meter = {
        ...baseProps
      };
      // Preserve meter-specific properties; fix any numeric colors back to hex
      if ((widget as any).scales) result.meter.scales = fixColorsDeep((widget as any).scales);
      break;

    case 'led':
      result.led = {
        ...baseProps
      };
      if ((widget as any).color) result.led.color = formatColor((widget as any).color);
      if ((widget as any).brightness !== undefined) result.led.brightness = (widget as any).brightness;
      break;

    case 'spinbox':
      result.spinbox = {
        ...baseProps
      };
      if ((widget as any).value !== undefined) result.spinbox.value = (widget as any).value;
      if ((widget as any).range_from !== undefined) result.spinbox.range_from = (widget as any).range_from;
      if ((widget as any).range_to !== undefined) result.spinbox.range_to = (widget as any).range_to;
      if ((widget as any).step !== undefined) result.spinbox.step = (widget as any).step;
      if ((widget as any).rollover !== undefined) result.spinbox.rollover = (widget as any).rollover;
      if ((widget as any).digit_count !== undefined) result.spinbox.digit_count = (widget as any).digit_count;
      if ((widget as any).decimal_places !== undefined) result.spinbox.decimal_places = (widget as any).decimal_places;
      break;

    case 'msgbox':
      result.msgbox = {
        ...baseProps
      };
      if ((widget as any).title !== undefined) result.msgbox.title = (widget as any).title;
      if ((widget as any).text !== undefined) result.msgbox.text = (widget as any).text;
      if ((widget as any).close_button !== undefined) result.msgbox.close_button = (widget as any).close_button;
      if ((widget as any).buttons) result.msgbox.buttons = (widget as any).buttons;
      break;

    default:
      result[(widget as any).type] = baseProps;
  }

  // Generic event-trigger passthrough: re-emit any `on_*` key (on_click,
  // on_value, on_press, on_long_press, on_release, …) that parseWidget copied
  // verbatim, even for triggers the switch above has no dedicated line for.
  // Without this, a widget's automations are silently dropped on export.
  const out = result[widget.type];
  if (out) {
    for (const key of Object.keys(widget)) {
      if (key.startsWith('on_') && out[key] === undefined) {
        out[key] = (widget as any)[key];
      }
    }
  }

  return result;
};

// Convert ESPHome YAML to internal config
export const yamlToConfig = (yamlString: string): LVGLConfig => {
  try {
    const parsed = yaml.load(yamlString, { schema: ESP_HOME_SCHEMA }) as any;
    
    // Check if parsed is valid
    if (!parsed || typeof parsed !== 'object') {
      throw new Error('Invalid YAML format: parsed result is empty or not an object');
    }
    
    // Extract style_definitions
    const style_definitions = parsed.style_definitions || parsed.lvgl?.style_definitions || [];
    const parsedStyles = style_definitions.map((style: any) => {
      const styleObj: StyleDefinition = { id: style.id };
      if (style.text_color != null) styleObj.text_color = parseColor(style.text_color);
      if (style.text_font) styleObj.text_font = style.text_font;
      if (style.bg_color != null) styleObj.bg_color = parseColor(style.bg_color);
      if (style.bg_grad_color != null) styleObj.bg_grad_color = parseColor(style.bg_grad_color);
      if (style.bg_grad_dir) styleObj.bg_grad_dir = style.bg_grad_dir;
      if (style.bg_opa) styleObj.bg_opa = style.bg_opa;
      if (style.border_color != null) styleObj.border_color = parseColor(style.border_color);
      if (style.border_width !== undefined) styleObj.border_width = style.border_width;
      if (style.border_opa) styleObj.border_opa = style.border_opa;
      if (style.radius !== undefined) styleObj.radius = style.radius;
      if (style.pad_all !== undefined) styleObj.pad_all = style.pad_all;
      if (style.pad_row !== undefined) styleObj.pad_row = style.pad_row;
      if (style.pad_column !== undefined) styleObj.pad_column = style.pad_column;
      if (style.width !== undefined) styleObj.width = style.width;
      if (style.height !== undefined) styleObj.height = style.height;
      if (style.text_align) styleObj.text_align = style.text_align;
      if (style.align) styleObj.align = style.align;
      
      // Copy any other properties
      Object.keys(style).forEach(key => {
        if (!styleObj.hasOwnProperty(key)) {
          (styleObj as any)[key] = style[key];
        }
      });
      
      return styleObj;
    });

    // Extract font definitions
    const fonts = parsed.font || parsed.lvgl?.font || [];
    const parsedFonts = fonts.map((font: any) => {
      const fontObj: any = {
        file: font.file,
        id: font.id,
        size: font.size
      };
      
      if (font.extras) fontObj.extras = font.extras;
      if (font.bpp !== undefined) fontObj.bpp = font.bpp;
      
      // Copy any other properties
      Object.keys(font).forEach(key => {
        if (!fontObj.hasOwnProperty(key)) {
          fontObj[key] = font[key];
        }
      });
      
      return fontObj;
    });
    
    // Extract pages from the YAML structure
    const pages = parsed.display?.[0]?.pages || parsed.lvgl?.pages || parsed.pages || [];
    
    // Extract bg_color
    const bg_color = parsed.bg_color || parsed.lvgl?.bg_color;
    
    // Extract top_layer
    const top_layer = parsed.top_layer || parsed.lvgl?.top_layer;
    let parsedTopLayer;
    if (top_layer && top_layer.widgets) {
      parsedTopLayer = {
        widgets: top_layer.widgets.map((w: any, index: number) => parseWidget(w, index, parsedStyles, parsedFonts))
      };
    }
    
    return {
      pages: pages.map((page: any) => ({
        id: page.id || 'main_page',
        widgets: (page.widgets || []).map((w: any, index: number) => parseWidget(w, index, parsedStyles, parsedFonts)),
        page_wrap: page.page_wrap,
        layout: page.layout,
        skip: page.skip
      })),
      style_definitions: parsedStyles.length > 0 ? parsedStyles : undefined,
      fonts: parsedFonts.length > 0 ? parsedFonts : undefined,
      bg_color: bg_color != null ? (typeof bg_color === 'number' ? formatRawColor(bg_color) : String(bg_color)) : undefined,
      top_layer: parsedTopLayer
    };
  } catch (error) {
    console.error('Error parsing YAML:', error);
    return {
      pages: [{
        id: 'main_page',
        widgets: []
      }]
    };
  }
};

// Helper function to resolve dimension from style or percentage
// For buttonmatrix widgets:
// - If width/height is missing or empty, uses value from style_definitions
// - If width/height is in %, converts to screen percentage (e.g., 100% of 320px = 320px)
// - Applies same logic for both direct values and style-inherited values
const resolveDimension = (
  value: any,
  styleName: string | undefined,
  styles: StyleDefinition[],
  dimension: 'width' | 'height',
  screenWidth: number = 320,
  screenHeight: number = 240
): number | string | undefined => {
  // If value is explicitly provided
  if (value !== undefined && value !== null && value !== '') {
    // Check if it's a percentage string
    if (typeof value === 'string' && value.includes('%')) {
      const percentage = parseFloat(value.replace('%', ''));
      const screenSize = dimension === 'width' ? screenWidth : screenHeight;
      return Math.round((percentage / 100) * screenSize);
    }
    return value;
  }
  
  // If no value provided, check if there's a style with this dimension
  if (styleName && styles.length > 0) {
    const style = styles.find(s => s.id === styleName);
    if (style && style[dimension] !== undefined) {
      // Check if style dimension is a percentage
      const styleDim = style[dimension];
      if (typeof styleDim === 'string' && styleDim.includes('%')) {
        const percentage = parseFloat(styleDim.replace('%', ''));
        const screenSize = dimension === 'width' ? screenWidth : screenHeight;
        return Math.round((percentage / 100) * screenSize);
      }
      return styleDim;
    }
  }
  
  return undefined;
};
// ESPHome's `styles:` property on an lvgl widget accepts either a single
// style id as a string ("my_style"), a space-separated string of several
// ("a b"), or a YAML list ([a, b]) — normalize all three to a plain array.
const normalizeStyleNames = (styleNames: string | string[] | undefined): string[] => {
  if (!styleNames) return [];
  if (Array.isArray(styleNames)) {
    return styleNames.filter((name): name is string => typeof name === 'string' && name.length > 0);
  }
  return styleNames.split(/\s+/).filter(Boolean);
};

const getStyleChain = (styleNames: string | string[] | undefined, styles: StyleDefinition[]): StyleDefinition[] => {
  return normalizeStyleNames(styleNames)
    .map(name => styles.find(style => style.id === name))
    .filter((style): style is StyleDefinition => Boolean(style));
};

const getMergedStyleValue = (styleNames: string | string[] | undefined, styles: StyleDefinition[], key: string): any => {
  const chain = getStyleChain(styleNames, styles);
  for (let index = chain.length - 1; index >= 0; index -= 1) {
    const value = (chain[index] as any)[key];
    if (value !== undefined) return value;
  }
  return undefined;
};

const getPaddingValue = (
  widgetData: any,
  styleNames: string | string[] | undefined,
  styles: StyleDefinition[],
  side: 'top' | 'right' | 'bottom' | 'left'
): number => {
  const specificKey = `pad_${side}`;
  const explicit = widgetData[specificKey];
  if (explicit !== undefined) return explicit;

  const styledSpecific = getMergedStyleValue(styleNames, styles, specificKey);
  if (styledSpecific !== undefined) return styledSpecific;

  const all = widgetData.pad_all ?? getMergedStyleValue(styleNames, styles, 'pad_all');
  return all ?? 0;
};

const approximateTextMetrics = (
  text: string,
  widgetData: any,
  styles: StyleDefinition[],
  fonts: FontDefinition[],
  options?: { minWidth?: number; extraHorizontalPadding?: number; extraVerticalPadding?: number; minHeight?: number; forceUppercase?: boolean }
) => measurePreviewText({
  text,
  fontId: widgetData.text_font || getMergedStyleValue(widgetData.styles, styles, 'text_font'),
  fonts,
  textLetterSpace: widgetData.text_letter_space ?? getMergedStyleValue(widgetData.styles, styles, 'text_letter_space') ?? 0,
  textLineSpace: widgetData.text_line_space ?? getMergedStyleValue(widgetData.styles, styles, 'text_line_space') ?? 0,
  padAll: widgetData.pad_all ?? getMergedStyleValue(widgetData.styles, styles, 'pad_all'),
  padTop: getPaddingValue(widgetData, widgetData.styles, styles, 'top'),
  padRight: getPaddingValue(widgetData, widgetData.styles, styles, 'right'),
  padBottom: getPaddingValue(widgetData, widgetData.styles, styles, 'bottom'),
  padLeft: getPaddingValue(widgetData, widgetData.styles, styles, 'left'),
  minWidth: options?.minWidth,
  minHeight: options?.minHeight,
  extraHorizontalPadding: options?.extraHorizontalPadding,
  extraVerticalPadding: options?.extraVerticalPadding,
  forceUppercase: options?.forceUppercase,
});

// Helper function to apply style properties to a widget for canvas RENDERING only.
// Tracks which properties it injected in widget._styleApplied[] so widgetToYaml can exclude them
// from export (avoiding duplicate output with the `styles:` reference).
const applyStyleToWidget = (widget: any, styleNames: string | string[] | undefined, styles: StyleDefinition[]): void => {
  if (!styleNames || styles.length === 0) return;

  // Same precedence as getMergedStyleValue(): when a widget references several
  // styles, a later name in the list overrides an earlier one. Walk the chain
  // highest-priority-first so the "only set if still undefined" guard below
  // lets the first (i.e. highest-priority) definition win.
  const chain = getStyleChain(styleNames, styles).reverse();
  if (chain.length === 0) return;

  if (!widget._styleApplied) widget._styleApplied = [];

  const maybeApply = (key: string, value: any) => {
    if (widget[key] === undefined && value !== undefined) {
      widget[key] = value;
      widget._styleApplied.push(key);
    }
  };

  for (const style of chain) {
    maybeApply('bg_color',      style.bg_color);
    maybeApply('bg_grad_color', style.bg_grad_color);
    maybeApply('bg_grad_dir',   style.bg_grad_dir);
    maybeApply('bg_opa',        style.bg_opa);
    maybeApply('border_color',  style.border_color);
    maybeApply('border_width',  style.border_width);
    maybeApply('border_opa',    style.border_opa);
    maybeApply('radius',        style.radius);
    maybeApply('width',         style.width);
    maybeApply('height',        style.height);
    maybeApply('min_width',     (style as any).min_width);
    maybeApply('min_height',    (style as any).min_height);
    maybeApply('pad_all',       style.pad_all);
    maybeApply('pad_top',       (style as any).pad_top);
    maybeApply('pad_right',     (style as any).pad_right);
    maybeApply('pad_bottom',    (style as any).pad_bottom);
    maybeApply('pad_left',      (style as any).pad_left);
    maybeApply('pad_row',       style.pad_row);
    maybeApply('pad_column',    style.pad_column);
    maybeApply('text_color',    style.text_color);
    maybeApply('text_font',     style.text_font);
    maybeApply('text_align',    style.text_align);
    maybeApply('text_letter_space', (style as any).text_letter_space);
    maybeApply('text_line_space',   (style as any).text_line_space);
    maybeApply('align',         style.align);
  }
};

// Helper function to parse a widget from YAML
const parseWidget = (w: any, index: number, styles: StyleDefinition[] = [], fonts: FontDefinition[] = []): Widget => {
          // Find widget type
          const widgetType = Object.keys(w)[0];
          const widgetData = w[widgetType];
          
          // Use ID only if explicitly provided in YAML
          const baseWidget: any = {
            type: widgetType
          };
          
          // Only set ID if it exists in YAML
          if (widgetData.id) {
            baseWidget.id = widgetData.id;
          } else {
            // Generate a temporary ID for internal use (but mark it as auto-generated)
            baseWidget.id = `${widgetType}_temp_${index + 1}`;
            baseWidget._autoGeneratedId = true;
          }
          
          // Only set x/y if explicitly provided
          if (widgetData.x !== undefined) baseWidget.x = widgetData.x;
          if (widgetData.y !== undefined) baseWidget.y = widgetData.y;

          // Auto-calculate dimensions based on content if not specified
          const autoWidth = !widgetData.width && widgetData.width !== 0;
          const autoHeight = !widgetData.height && widgetData.height !== 0;
          
          if (autoWidth || autoHeight) {
            if (widgetType === 'label' && widgetData.text) {
              const metrics = approximateTextMetrics(widgetData.text, widgetData, styles, fonts);
              if (autoWidth) baseWidget._measuredWidth = metrics.width;
              if (autoHeight) baseWidget._measuredHeight = metrics.height;
            } else if (widgetType === 'button') {
              const buttonText = widgetData.widgets?.[0]?.label?.text || widgetData.text || 'Button';
              const metrics = approximateTextMetrics(buttonText, widgetData, styles, fonts, {
                minWidth: 72,
                extraHorizontalPadding: 24,
                extraVerticalPadding: 12,
                minHeight: 36,
                forceUppercase: true,
              });
              if (autoWidth) baseWidget._measuredWidth = metrics.width;
              if (autoHeight) baseWidget._measuredHeight = Math.max(metrics.height, 36);
            } else if (widgetType === 'obj') {
              // For containers, use SIZE_CONTENT or calculate from children
              if (widgetData.height === 'SIZE_CONTENT') {
                baseWidget.height = 'SIZE_CONTENT';
              } else if (autoHeight && widgetData.widgets) {
                // Calculate based on children positions
                let maxY = 0;
                widgetData.widgets.forEach((child: any) => {
                  const childData = child[Object.keys(child)[0]];
                  const childY = childData.y || 0;
                  const childHeight = childData.height || 50;
                  maxY = Math.max(maxY, childY + childHeight);
                });
                baseWidget.height = Math.max(maxY + (widgetData.pad_all || 8), 60);
              } else if (autoHeight) {
                baseWidget.height = 100;
              }
              if (autoWidth) {
                baseWidget.width = widgetData.width || 200;
              }
            } else {
              // Default dimensions for other widgets
              if (autoWidth) {
                baseWidget.width = widgetType === 'slider'
                  ? 120
                  : widgetType === 'switch'
                    ? 60
                    : widgetType === 'spinbox'
                      ? 110
                      : widgetType === 'msgbox'
                        ? 180
                        : 100;
              }
              if (autoHeight) {
                baseWidget.height = widgetType === 'slider'
                  ? 10
                  : widgetType === 'switch'
                    ? 30
                    : widgetType === 'spinbox'
                      ? 36
                      : widgetType === 'msgbox'
                        ? 120
                        : 50;
              }
            }
          }

          // Copy all properties from widgetData
          const resolvedWidth = resolveDimension(widgetData.width, widgetData.styles, styles, 'width');
          const resolvedHeight = resolveDimension(widgetData.height, widgetData.styles, styles, 'height');
          if (widgetData.width !== undefined) {
            baseWidget.width = resolvedWidth ?? widgetData.width;
            baseWidget._explicitWidth = true;
          } else if (resolvedWidth !== undefined) {
            baseWidget.width = resolvedWidth;
            baseWidget._styleApplied = [...(baseWidget._styleApplied || []), 'width'];
          }
          if (widgetData.height !== undefined) {
            baseWidget.height = resolvedHeight ?? widgetData.height;
            baseWidget._explicitHeight = true;
          } else if (resolvedHeight !== undefined) {
            baseWidget.height = resolvedHeight;
            baseWidget._styleApplied = [...(baseWidget._styleApplied || []), 'height'];
          }
          if (widgetData.bg_color != null) baseWidget.bg_color = parseColor(widgetData.bg_color);
          if (widgetData.bg_grad_color != null) baseWidget.bg_grad_color = parseColor(widgetData.bg_grad_color);
          if (widgetData.bg_grad_dir) baseWidget.bg_grad_dir = widgetData.bg_grad_dir;
          if (widgetData.bg_opa) baseWidget.bg_opa = widgetData.bg_opa;
          if (widgetData.border_color != null) baseWidget.border_color = parseColor(widgetData.border_color);
          if (widgetData.border_width !== undefined) baseWidget.border_width = widgetData.border_width;
          if (widgetData.border_opa) baseWidget.border_opa = widgetData.border_opa;
          if (widgetData.radius !== undefined) baseWidget.radius = widgetData.radius;
          if (widgetData.pad_all !== undefined) baseWidget.pad_all = widgetData.pad_all;
          if (widgetData.pad_top !== undefined) baseWidget.pad_top = widgetData.pad_top;
          if (widgetData.pad_right !== undefined) baseWidget.pad_right = widgetData.pad_right;
          if (widgetData.pad_bottom !== undefined) baseWidget.pad_bottom = widgetData.pad_bottom;
          if (widgetData.pad_left !== undefined) baseWidget.pad_left = widgetData.pad_left;
          if (widgetData.pad_row !== undefined) baseWidget.pad_row = widgetData.pad_row;
          if (widgetData.pad_column !== undefined) baseWidget.pad_column = widgetData.pad_column;
          if (widgetData.align) baseWidget.align = widgetData.align;
          if (widgetData.styles) baseWidget.styles = widgetData.styles;
          if (widgetData.text_font) baseWidget.text_font = widgetData.text_font;
          if (widgetData.text_align) baseWidget.text_align = widgetData.text_align;
          if (widgetData.text_letter_space !== undefined) baseWidget.text_letter_space = widgetData.text_letter_space;
          if (widgetData.text_line_space !== undefined) baseWidget.text_line_space = widgetData.text_line_space;
          if (widgetData.text_color != null) baseWidget.text_color = parseColor(widgetData.text_color);
          if (widgetData.hidden !== undefined) baseWidget.hidden = widgetData.hidden;
          if (widgetData.layout) baseWidget.layout = widgetData.layout;
          if (widgetData.flex_flow) baseWidget.flex_flow = widgetData.flex_flow;
          if (widgetData.flex_align) baseWidget.flex_align = widgetData.flex_align;
          if (widgetData.grid_rows) baseWidget.grid_rows = widgetData.grid_rows;
          if (widgetData.grid_cols) baseWidget.grid_cols = widgetData.grid_cols;

          // Generic event-trigger passthrough: copy any `on_*` key (on_click,
          // on_value, on_press, on_long_press, on_release, …) verbatim, so a
          // widget's automations survive a visual-editor round trip even for
          // trigger names the editor has no dedicated UI for.
          for (const key of Object.keys(widgetData)) {
            if (key.startsWith('on_') && baseWidget[key] === undefined) {
              baseWidget[key] = widgetData[key];
            }
          }

          // Apply style properties to widget if a style is referenced
          applyStyleToWidget(baseWidget, widgetData.styles, styles);

          // Type-specific properties
          switch (widgetType) {
            case 'label':
              if (widgetData.text !== undefined) baseWidget.text = widgetData.text;
              if (widgetData.text_color != null) baseWidget.text_color = parseColor(widgetData.text_color);
              break;
            case 'button':
            case 'obj':
              if (widgetData.widgets) {
                baseWidget.widgets = widgetData.widgets.map((w: any, idx: number) => parseWidget(w, idx, styles, fonts));
              }
              break;
            case 'line':
              if (widgetData.points) {
                // Parse points from YAML format (can be array of strings or array of arrays)
                baseWidget.points = widgetData.points.map((point: any) => {
                  if (typeof point === 'string') {
                    const [x, y] = point.split(',').map(s => parseFloat(s.trim()));
                    return [x, y] as [number, number];
                  } else if (Array.isArray(point)) {
                    return [point[0], point[1]] as [number, number];
                  }
                  return [0, 0] as [number, number];
                });
              }
              if (widgetData.line_color != null) baseWidget.line_color = parseColor(widgetData.line_color);
              if (widgetData.line_width !== undefined) baseWidget.line_width = widgetData.line_width;
              if (widgetData.line_dash_width !== undefined) baseWidget.line_dash_width = widgetData.line_dash_width;
              if (widgetData.line_dash_gap !== undefined) baseWidget.line_dash_gap = widgetData.line_dash_gap;
              if (widgetData.line_rounded !== undefined) baseWidget.line_rounded = widgetData.line_rounded;
              break;
            case 'slider':
            case 'bar':
            case 'arc':
              if (widgetData.min_value !== undefined) baseWidget.min_value = widgetData.min_value;
              if (widgetData.max_value !== undefined) baseWidget.max_value = widgetData.max_value;
              if (widgetData.value !== undefined) baseWidget.value = widgetData.value;
              break;
            case 'switch':
            case 'checkbox':
              if (widgetData.checked !== undefined) baseWidget.checked = widgetData.checked;
              if (widgetData.text !== undefined) baseWidget.text = widgetData.text;
              break;
            case 'dropdown':
            case 'roller':
              if (widgetData.options) baseWidget.options = widgetData.options;
              if (widgetData.selected !== undefined) baseWidget.selected = widgetData.selected;
              break;
            case 'led':
              if (widgetData.color != null) baseWidget.color = parseColor(widgetData.color);
              if (widgetData.brightness !== undefined) baseWidget.brightness = widgetData.brightness;
              break;
            case 'spinbox':
              if (widgetData.value !== undefined) baseWidget.value = widgetData.value;
              if (widgetData.range_from !== undefined) baseWidget.range_from = widgetData.range_from;
              if (widgetData.range_to !== undefined) baseWidget.range_to = widgetData.range_to;
              if (widgetData.step !== undefined) baseWidget.step = widgetData.step;
              if (widgetData.rollover !== undefined) baseWidget.rollover = widgetData.rollover;
              if (widgetData.digit_count !== undefined) baseWidget.digit_count = widgetData.digit_count;
              if (widgetData.decimal_places !== undefined) baseWidget.decimal_places = widgetData.decimal_places;
              break;
            case 'msgbox':
              if (widgetData.title !== undefined) baseWidget.title = widgetData.title;
              if (widgetData.text !== undefined) baseWidget.text = widgetData.text;
              if (widgetData.close_button !== undefined) baseWidget.close_button = widgetData.close_button;
              if (widgetData.buttons) baseWidget.buttons = widgetData.buttons;
              break;
            case 'buttonmatrix':
              if (widgetData.rows) baseWidget.rows = widgetData.rows;
              if (widgetData.items) baseWidget.items = widgetData.items;
              if (widgetData.one_checked !== undefined) baseWidget.one_checked = widgetData.one_checked;
              if (widgetData.outline_width !== undefined) baseWidget.outline_width = widgetData.outline_width;
              break;
            case 'meter':
              if (widgetData.scales) baseWidget.scales = widgetData.scales;
              break;
          }

          return baseWidget as Widget;
        };


